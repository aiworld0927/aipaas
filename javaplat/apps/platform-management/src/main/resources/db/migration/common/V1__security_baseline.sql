create table sec_users (
    id varchar(64) primary key,
    tenant_id varchar(64) not null,
    username varchar(64) not null,
    display_name varchar(64) not null,
    email_ciphertext text,
    password_hash varchar(100) not null,
    status varchar(16) not null,
    failed_attempts integer not null default 0,
    locked_until timestamp with time zone,
    auth_version bigint not null default 1,
    last_login_at timestamp with time zone,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    unique (tenant_id, username)
);

create table sec_roles (
    id varchar(64) primary key,
    tenant_id varchar(64) not null,
    code varchar(32) not null,
    name varchar(64) not null,
    built_in boolean not null default false,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    unique (tenant_id, code)
);

create table sec_permissions (
    tenant_id varchar(64) not null,
    code varchar(64) not null,
    name varchar(128) not null,
    domain varchar(64) not null,
    description varchar(512),
    primary key (tenant_id, code)
);

create table sec_role_permissions (
    tenant_id varchar(64) not null,
    role_id varchar(64) not null,
    permission_code varchar(64) not null,
    primary key (tenant_id, role_id, permission_code),
    foreign key (role_id) references sec_roles(id)
);

create table sec_user_roles (
    tenant_id varchar(64) not null,
    user_id varchar(64) not null,
    role_id varchar(64) not null,
    primary key (tenant_id, user_id, role_id),
    foreign key (user_id) references sec_users(id),
    foreign key (role_id) references sec_roles(id)
);

create table sec_role_kb_grants (
    tenant_id varchar(64) not null,
    role_id varchar(64) not null,
    kb_id varchar(64) not null,
    permission_code varchar(64) not null,
    primary key (tenant_id, role_id, kb_id, permission_code),
    foreign key (role_id) references sec_roles(id)
);

create table sec_refresh_tokens (
    token_hash varchar(64) primary key,
    id varchar(64) not null unique,
    tenant_id varchar(64) not null,
    user_id varchar(64) not null,
    session_id varchar(64) not null,
    expires_at timestamp with time zone not null,
    revoked_at timestamp with time zone,
    replaced_by varchar(64),
    created_at timestamp with time zone not null,
    foreign key (user_id) references sec_users(id)
);
create index idx_refresh_session on sec_refresh_tokens(session_id);

create table sec_revoked_tokens (
    jti varchar(64) primary key,
    expires_at timestamp with time zone not null
);

create table sec_audit_logs (
    sequence_no bigint generated by default as identity unique,
    id varchar(64) primary key,
    tenant_id varchar(64) not null,
    actor_id varchar(64) not null,
    actor_name varchar(128),
    action varchar(96) not null,
    object_type varchar(64) not null,
    object_id varchar(128),
    result varchar(16) not null,
    ip varchar(64),
    user_agent varchar(512),
    trace_id varchar(128) not null,
    detail_json text,
    previous_hash varchar(64) not null,
    entry_hash varchar(64) not null,
    env varchar(32) not null default 'prod',
    archive boolean not null default false,
    created_at timestamp with time zone not null
);
create index idx_audit_search on sec_audit_logs(tenant_id, action, actor_id, object_type, object_id, result, created_at);
create index idx_audit_env on sec_audit_logs(env, archive, created_at);

create table sec_policies (
    rule_type varchar(32) primary key,
    enabled boolean not null,
    action varchar(16) not null,
    threshold double precision,
    rule_version varchar(32) not null,
    updated_at timestamp with time zone not null,
    updated_by varchar(64)
);

create table sec_rules (
    rule_id varchar(64) primary key,
    rule_type varchar(32) not null,
    pattern varchar(512) not null,
    match_type varchar(16) not null,
    description varchar(256),
    enabled boolean not null default true,
    weight double precision not null default 1.0
);
create index idx_rules_type on sec_rules(rule_type, enabled);

create table knowledge_bases (
    id varchar(64) primary key,
    tenant_id varchar(64) not null,
    name varchar(128) not null,
    status varchar(16) not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

create table documents (
    id varchar(64) primary key,
    tenant_id varchar(64) not null,
    kb_id varchar(64) not null,
    filename_ciphertext text not null,
    standard_no_ciphertext text,
    object_key varchar(512) not null,
    format varchar(16) not null,
    size_bytes bigint not null,
    status varchar(16) not null,
    uploader_id varchar(64) not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    foreign key (kb_id) references knowledge_bases(id)
);
create index idx_documents_kb on documents(tenant_id, kb_id, created_at);

create table ingest_tasks (
    id varchar(64) primary key,
    tenant_id varchar(64) not null,
    document_id varchar(64) not null,
    kb_id varchar(64) not null,
    status varchar(16) not null,
    stage varchar(16) not null,
    progress integer not null,
    retry_count integer not null default 0,
    max_retries integer not null default 2,
    queued_at timestamp with time zone not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    foreign key (document_id) references documents(id)
);
